const dictionaries: Record<string, Dictionary> = { 'zh-CN': zhCN };
const active = dictionaries['zh-CN'];

export function has(key: string): boolean {
  return Object.hasOwn(active, key);
}

/** The message for `key` with `{placeholders}` filled in; the key itself when missing. */
export function t(key: string, values: Record<string, string | number> = {}): string {
  const template = active[key] ?? key;
  return template.replace(/\{(\w+)\}/g, (match, name: string) => (Object.hasOwn(values, name) ? String(values[name]) : match));
}

export function hintFor(code: string): string | undefined {
  return has(`hint.${code}`) ? t(`hint.${code}`) : undefined;
}

/** Every key, for the test that checks no message is missing. */
export const messageKeys = (): string[] => Object.keys(active);
